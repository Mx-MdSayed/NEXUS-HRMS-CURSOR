import { PERMISSIONS } from '@/constants/permissions'
import type { PermissionDefinition } from '../types'

function def(
  code: PermissionDefinition['code'],
  name: string,
  module: string,
  action: string,
  description: string,
): PermissionDefinition {
  return {
    id: `perm_${code.replace(/\./g, '_')}`,
    code,
    name,
    module,
    category: module,
    action,
    description,
    isSystemPermission: true,
  }
}

